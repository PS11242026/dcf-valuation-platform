"""Assemble the publication-grade research PACKAGE -> reports/paper/.

This is a presentation layer: it reads already-produced report artifacts (JSON/CSV under reports/) and emits

    reports/paper/master_research_report.md   -- modular 11-section master, every number cited to its source
    reports/paper/tables/*.csv                 -- standalone exhibit tables (copied / derived)
    reports/paper/figures/*.png                -- via scripts.paper.figures (matplotlib-guarded)

It does NOT re-run the DCF, the backtests, or the studies -- run those first (final_institutional_validation,
run_validation_suites, portfolio_metrics, risk_ablation, sector_attribution, survivorship_*, capacity_costs,
rebalance_horizon). The master is deliberately format-agnostic: each section can be promoted into an FAJ-style
paper, a CFA Research Foundation brief, an SSRN working paper, or an internal memo with minimal rewriting.

Usage:
    python -m scripts.paper.build_paper
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from scripts.paper import figures

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / "reports"
PORT = REPORTS / "portfolio"
PAPER = REPORTS / "paper"
TABLES = PAPER / "tables"


def _j(path: Path) -> dict | None:
    return json.load(open(path)) if path.exists() else None


def _csv(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def _pct(x, d=1) -> str:
    return "N/A" if x is None or (isinstance(x, float) and pd.isna(x)) else f"{x * 100:.{d}f}%"


def _usd(x) -> str:
    if x is None or (isinstance(x, float) and (pd.isna(x))):
        return "N/A"
    x = float(x)
    for unit, div in (("B", 1e9), ("M", 1e6), ("k", 1e3)):
        if x >= div:
            return f"${x / div:.1f}{unit}"
    return f"${x:.0f}"


# --------------------------------------------------------------------------- tables
def build_tables() -> list[str]:
    TABLES.mkdir(parents=True, exist_ok=True)
    made: list[str] = []
    # straight copies of canonical exhibit CSVs
    for src, dst in [("risk_ablation.csv", "risk_ablation.csv"),
                     ("capacity_costs.csv", "capacity_costs.csv"),
                     ("sector_attribution.csv", "sector_attribution.csv"),
                     ("allocation_study.csv", "allocation_study.csv"),
                     ("factor_uniqueness.csv", "factor_uniqueness.csv")]:
        s = PORT / src
        if s.exists():
            (TABLES / dst).write_text(s.read_text(encoding="utf-8"), encoding="utf-8")
            made.append(dst)
    # derive predictive_power.csv from the institutional validation JSON
    val = _j(REPORTS / "final_institutional_validation.json")
    if val and "overall" in val:
        rows = []
        for hz, b in val["overall"].items():
            rows.append({
                "horizon": hz, "n_obs": b.get("n"), "n_periods": b.get("n_periods"),
                "ic_equal_weight": round(b.get("ic_equal_weight", float("nan")), 4),
                "ic_obs_weighted": round(b.get("ic_obs_weighted", float("nan")), 4),
                "spearman_pooled": round(b.get("spearman_pooled", float("nan")), 4),
                "hit_rate": round(b.get("hit_rate", float("nan")), 4),
                "q5_minus_q1": round(b.get("long_short_q5_minus_q1", float("nan")), 4),
            })
        pd.DataFrame(rows).to_csv(TABLES / "predictive_power.csv", index=False)
        made.append("predictive_power.csv")
    return made


